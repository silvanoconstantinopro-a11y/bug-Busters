const { Pool } = require('pg');

let pool;
let initialization;

function getPool() {
  if (!process.env.DATABASE_URL) {
    throw new Error('DATABASE_URL tem de estar configurada.');
  }

  if (!pool) {
    pool = new Pool({
      connectionString: process.env.DATABASE_URL,
      max: process.env.VERCEL ? 1 : 10,
      idleTimeoutMillis: 10000,
      connectionTimeoutMillis: 10000,
    });
  }

  return pool;
}

function postgresPlaceholders(sql) {
  let index = 0;
  return sql.replace(/\?/g, () => `$${++index}`);
}

function query(sql, values = []) {
  return getPool().query(postgresPlaceholders(sql), values);
}

async function transaction(callback) {
  const client = await getPool().connect();

  try {
    await client.query('BEGIN');
    const result = await callback((sql, values = []) =>
      client.query(postgresPlaceholders(sql), values));
    await client.query('COMMIT');
    return result;
  } catch (error) {
    await client.query('ROLLBACK');
    throw error;
  } finally {
    client.release();
  }
}

async function initDatabase() {
  if (!initialization) {
    initialization = getPool().query(`
      CREATE TABLE IF NOT EXISTS users (
        id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        email TEXT UNIQUE NOT NULL,
        password_hash TEXT NOT NULL,
        full_name TEXT NOT NULL,
        role TEXT NOT NULL DEFAULT 'colaborador',
        is_active BOOLEAN NOT NULL DEFAULT TRUE,
        last_login TIMESTAMPTZ,
        created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
      );
      CREATE TABLE IF NOT EXISTS clients (
        id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        full_name TEXT NOT NULL,
        email TEXT,
        country_code TEXT NOT NULL DEFAULT '+244',
        phone TEXT NOT NULL,
        country TEXT NOT NULL,
        city TEXT,
        organization TEXT,
        created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
        updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
      );
      CREATE TABLE IF NOT EXISTS project_requests (
        id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        reference TEXT UNIQUE NOT NULL,
        confirmation_token TEXT UNIQUE NOT NULL,
        client_id INTEGER NOT NULL REFERENCES clients(id),
        title TEXT NOT NULL,
        objective TEXT NOT NULL,
        description TEXT NOT NULL,
        project_type TEXT NOT NULL,
        client_category TEXT NOT NULL,
        industry TEXT,
        budget_range TEXT,
        desired_deadline TEXT,
        current_stage TEXT,
        status TEXT NOT NULL DEFAULT 'new',
        priority TEXT NOT NULL DEFAULT 'normal',
        assigned_to_id INTEGER REFERENCES users(id) ON DELETE SET NULL,
        privacy_consent BOOLEAN NOT NULL DEFAULT FALSE,
        created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
        updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
      );
      CREATE TABLE IF NOT EXISTS request_status_history (
        id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        request_id INTEGER NOT NULL REFERENCES project_requests(id) ON DELETE CASCADE,
        changed_by_id INTEGER REFERENCES users(id) ON DELETE SET NULL,
        previous_status TEXT,
        new_status TEXT NOT NULL,
        comment TEXT,
        created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
      );
      CREATE TABLE IF NOT EXISTS audit_logs (
        id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        actor_id INTEGER REFERENCES users(id) ON DELETE SET NULL,
        action TEXT NOT NULL,
        entity TEXT NOT NULL,
        entity_id TEXT,
        metadata TEXT,
        created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
      );
      CREATE TABLE IF NOT EXISTS services (
        id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        name TEXT NOT NULL,
        slug TEXT UNIQUE NOT NULL,
        description TEXT NOT NULL,
        icon TEXT,
        is_active BOOLEAN NOT NULL DEFAULT TRUE,
        sort_order INTEGER NOT NULL DEFAULT 0
      );
      CREATE TABLE IF NOT EXISTS portfolio_projects (
        id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        title TEXT NOT NULL,
        slug TEXT UNIQUE NOT NULL,
        summary TEXT NOT NULL,
        description TEXT,
        technologies TEXT,
        cover_image TEXT,
        demo_url TEXT,
        repository_url TEXT,
        is_published BOOLEAN NOT NULL DEFAULT TRUE,
        created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
      );
      CREATE TABLE IF NOT EXISTS team_members (
        id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        name TEXT NOT NULL,
        role TEXT NOT NULL,
        biography TEXT,
        photo_url TEXT,
        linkedin_url TEXT,
        sort_order INTEGER NOT NULL DEFAULT 0,
        is_published BOOLEAN NOT NULL DEFAULT TRUE
      );
      CREATE TABLE IF NOT EXISTS settings (
        key TEXT PRIMARY KEY,
        value TEXT
      );
      CREATE TABLE IF NOT EXISTS project_request_sequences (
        year INTEGER PRIMARY KEY,
        last_value INTEGER NOT NULL
      );
      CREATE TABLE IF NOT EXISTS rate_limit_hits (
        key TEXT PRIMARY KEY,
        hits INTEGER NOT NULL,
        reset_at TIMESTAMPTZ NOT NULL
      );
      CREATE TABLE IF NOT EXISTS session (
        sid VARCHAR NOT NULL PRIMARY KEY,
        sess JSON NOT NULL,
        expire TIMESTAMP(6) NOT NULL
      );
      CREATE INDEX IF NOT EXISTS idx_requests_status ON project_requests(status);
      CREATE INDEX IF NOT EXISTS idx_requests_client ON project_requests(client_id);
      CREATE INDEX IF NOT EXISTS idx_history_request ON request_status_history(request_id);
      CREATE INDEX IF NOT EXISTS idx_session_expire ON session(expire);
      CREATE INDEX IF NOT EXISTS idx_rate_limit_reset ON rate_limit_hits(reset_at);
    `).catch((error) => {
      initialization = null;
      throw error;
    });
  }

  await initialization;
}

async function closePool() {
  if (pool) {
    const currentPool = pool;
    pool = null;
    initialization = null;
    await currentPool.end();
  }
}

module.exports = { getPool, query, transaction, initDatabase, closePool };
